// Bundles Leaflet's CSS into styles.css, scoped under .mythical-map-view (design D5).
//   node scripts/scope-leaflet-css.mjs           (or: npm run css)   rewrite the generated section
//   node scripts/scope-leaflet-css.mjs --check                       exit 1 if styles.css is stale
//
// Obsidian loads only styles.css, and every rule there must be scoped under
// .mythical-map-view (CLAUDE.md). The generated block sits between the BEGIN/END
// marker comments; everything outside the markers is hand-written and left as is.
//
// Declarations that reference url(...) (marker and layer-control images, IE VML
// behaviour) are dropped: the plugin draws its own icons and bundles no images.
// The output is deterministic, so a test can assert the committed copy is current.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const SCOPE = ".mythical-map-view";
export const BEGIN_MARKER = "/* BEGIN leaflet.css — generated by scripts/scope-leaflet-css.mjs (npm run css); do not edit */";
export const END_MARKER = "/* END leaflet.css */";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const LEAFLET_CSS = join(ROOT, "node_modules/leaflet/dist/leaflet.css");
export const STYLES_CSS = join(ROOT, "styles.css");

/** Strip comments from CSS text. */
function stripComments(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, "");
}

/**
 * Parse CSS into a tree of `{ kind: "rule", selectors, declarations }` and
 * `{ kind: "at", prelude, children }` nodes. Supports the subset Leaflet uses:
 * plain rules and block at-rules (such as @media) containing plain rules.
 */
export function parseCss(css) {
  const text = stripComments(css);
  let i = 0;

  function parseBlock(untilClose) {
    const nodes = [];
    for (;;) {
      while (i < text.length && /\s/.test(text[i])) i++;
      if (i >= text.length) {
        if (untilClose) throw new Error("Unexpected end of CSS: missing }");
        return nodes;
      }
      if (text[i] === "}") {
        if (!untilClose) throw new Error(`Unexpected } at offset ${i}`);
        i++;
        return nodes;
      }
      const open = text.indexOf("{", i);
      if (open < 0) throw new Error(`Expected { after offset ${i}`);
      const prelude = text.slice(i, open).trim();
      i = open + 1;
      if (prelude.startsWith("@")) {
        nodes.push({ kind: "at", prelude: prelude.replace(/\s+/g, " "), children: parseBlock(true) });
      } else {
        const close = text.indexOf("}", i);
        if (close < 0) throw new Error("Unexpected end of CSS: missing }");
        const body = text.slice(i, close);
        i = close + 1;
        nodes.push({
          kind: "rule",
          selectors: prelude.split(",").map((s) => s.trim().replace(/\s+/g, " ")).filter(Boolean),
          declarations: body.split(";").map((d) => d.trim().replace(/\s+/g, " ")).filter(Boolean),
        });
      }
    }
  }

  return parseBlock(false);
}

/** All selectors in a parsed tree, at any nesting depth. */
export function allSelectors(nodes) {
  return nodes.flatMap((n) => (n.kind === "rule" ? n.selectors : allSelectors(n.children)));
}

/**
 * Scope one selector under `.mythical-map-view`. Leaflet puts `leaflet-dragging`
 * on `<body>`, an ancestor of the view, so that class stays in front of the scope.
 */
export function scopeSelector(selector) {
  const dragging = /^\.leaflet-dragging\s+/;
  if (dragging.test(selector)) return `.leaflet-dragging ${SCOPE} ${selector.replace(dragging, "")}`;
  return `${SCOPE} ${selector}`;
}

function scopeNodes(nodes) {
  const out = [];
  for (const n of nodes) {
    if (n.kind === "at") {
      const children = scopeNodes(n.children);
      if (children.length > 0) out.push({ ...n, children });
      continue;
    }
    const declarations = n.declarations.filter((d) => !/url\(/i.test(d));
    if (declarations.length === 0) continue;
    out.push({ kind: "rule", selectors: n.selectors.map(scopeSelector), declarations });
  }
  return out;
}

function printNodes(nodes, indent = "") {
  return nodes
    .map((n) => {
      if (n.kind === "at") return `${indent}${n.prelude} {\n${printNodes(n.children, indent + "  ")}\n${indent}}`;
      const sel = n.selectors.map((s) => indent + s).join(",\n");
      const body = n.declarations.map((d) => `${indent}  ${d};`).join("\n");
      return `${sel} {\n${body}\n${indent}}`;
    })
    .join("\n");
}

/** Leaflet's CSS with every selector scoped and url() declarations removed. */
export function scopeLeafletCss(css) {
  return printNodes(scopeNodes(parseCss(css))) + "\n";
}

/** Replace (or append) the generated section of `styles` with `generated`. */
export function spliceGenerated(styles, generated) {
  const block = `${BEGIN_MARKER}\n${generated}${END_MARKER}\n`;
  const begin = styles.indexOf(BEGIN_MARKER);
  const end = styles.indexOf(END_MARKER);
  if (begin < 0 || end < 0) return `${styles.replace(/\n*$/, "\n\n")}${block}`;
  return styles.slice(0, begin) + block + styles.slice(end + END_MARKER.length).replace(/^\n/, "");
}

/** styles.css as it should be, given the current leaflet.css. */
export function expectedStyles(stylesText = readFileSync(STYLES_CSS, "utf8"), leafletText = readFileSync(LEAFLET_CSS, "utf8")) {
  return spliceGenerated(stylesText, scopeLeafletCss(leafletText));
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const current = readFileSync(STYLES_CSS, "utf8");
  const next = expectedStyles(current);
  if (process.argv.includes("--check")) {
    if (current !== next) {
      console.error("styles.css is stale: run `npm run css`.");
      process.exit(1);
    }
  } else if (current !== next) {
    writeFileSync(STYLES_CSS, next);
    console.log("styles.css: Leaflet CSS section updated.");
  }
}
